
-- 1. Users
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) NOT NULL,
                       password VARCHAR(255) NOT NULL,
                       user_type VARCHAR(255) NOT NULL,
                       status VARCHAR(255) NOT NULL,
                       last_access TIMESTAMP,
                       creation_date DATE
);

-- 2. Companies
CREATE TABLE companies (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           user_id BIGINT NOT NULL,
                           cnpj VARCHAR(14) NOT NULL,
                           registered_company_name VARCHAR(255) NOT NULL,
                           average_revenue NUMERIC(12, 2) NOT NULL,
                           time_months INTEGER NOT NULL,
                           number_of_employees INTEGER NOT NULL,
                           status VARCHAR(255) NOT NULL,
                           creation_date DATE,

                           CONSTRAINT fk_companies_user
                               FOREIGN KEY (user_id) REFERENCES users(id)
);

-- 3. Default occurrences
CREATE TABLE default_occurrence (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    firm_id BIGINT NOT NULL,
                                    occurrence_date DATE NOT NULL,
                                    amount_due NUMERIC(12, 2) NOT NULL,
                                    status_resolved BOOLEAN NOT NULL,
                                    description VARCHAR(255),
                                    status VARCHAR(255) NOT NULL,
                                    creation_date DATE,

                                    CONSTRAINT fk_default_occurrence_company
                                        FOREIGN KEY (firm_id) REFERENCES companies(id)
);

-- 4. Calculated scores
CREATE TABLE calculated_score (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  firm_id BIGINT NOT NULL,
                                  user_id BIGINT NOT NULL,
                                  score_value INTEGER NOT NULL,
                                  risk_band VARCHAR(255) NOT NULL,
                                  justification TEXT NOT NULL,
                                  factors_json JSONB NOT NULL,
                                  status VARCHAR(255) NOT NULL,
                                  calculation_date DATE,

                                  CONSTRAINT fk_calculated_score_company
                                      FOREIGN KEY (firm_id) REFERENCES companies(id),

                                  CONSTRAINT fk_calculated_score_user
                                      FOREIGN KEY (user_id) REFERENCES users(id)
);

-- 5. Weight configurations
CREATE TABLE weight_configuration (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      formula_type VARCHAR(255) NOT NULL,
                                      revenue_weight NUMERIC(4, 2) NOT NULL,
                                      time_weight NUMERIC(4, 2) NOT NULL,
                                      default_weight NUMERIC(4, 2) NOT NULL,
                                      max_revenue_reference NUMERIC(38, 2) NOT NULL,
                                      max_time_reference_months INTEGER NOT NULL,
                                      low_risk_threshold INTEGER NOT NULL,
                                      medium_risk_threshold INTEGER NOT NULL,
                                      updated_by_user_id BIGINT NOT NULL,
                                      status VARCHAR(255) NOT NULL,
                                      creation_date DATE,

                                      CONSTRAINT fk_weight_configuration_user
                                          FOREIGN KEY (updated_by_user_id) REFERENCES users(id)
);

-- Foreign key indexes
CREATE INDEX idx_companies_user_id
    ON companies(user_id);

CREATE INDEX idx_default_occurrence_firm_id
    ON default_occurrence(firm_id);

CREATE INDEX idx_calculated_score_firm_id
    ON calculated_score(firm_id);

CREATE INDEX idx_calculated_score_user_id
    ON calculated_score(user_id);

CREATE INDEX idx_weight_configuration_updated_by_user_id
    ON weight_configuration(updated_by_user_id);